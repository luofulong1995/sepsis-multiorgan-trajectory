DROP TABLE IF EXISTS eicu_sepsis_daily_wide;
CREATE TABLE eicu_sepsis_daily_wide AS
SELECT c.stay_id,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=0 THEN lab.last_val END) AS plt_last_d0,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=1 THEN lab.last_val END) AS plt_last_d1,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=2 THEN lab.last_val END) AS plt_last_d2,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=0 THEN lab.med_val END) AS plt_med_d0,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=1 THEN lab.med_val END) AS plt_med_d1,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=2 THEN lab.med_val END) AS plt_med_d2,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=0 THEN lab.worst_val END) AS plt_worst_d0,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=1 THEN lab.worst_val END) AS plt_worst_d1,
  MAX(CASE WHEN lab.labname='platelets x 1000' AND lab.day=2 THEN lab.worst_val END) AS plt_worst_d2,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=0 THEN lab.last_val END) AS cre_last_d0,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=1 THEN lab.last_val END) AS cre_last_d1,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=2 THEN lab.last_val END) AS cre_last_d2,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=0 THEN lab.med_val END) AS cre_med_d0,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=1 THEN lab.med_val END) AS cre_med_d1,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=2 THEN lab.med_val END) AS cre_med_d2,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=0 THEN lab.worst_val END) AS cre_worst_d0,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=1 THEN lab.worst_val END) AS cre_worst_d1,
  MAX(CASE WHEN lab.labname='creatinine' AND lab.day=2 THEN lab.worst_val END) AS cre_worst_d2,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=0 THEN lab.last_val END) AS lac_last_d0,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=1 THEN lab.last_val END) AS lac_last_d1,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=2 THEN lab.last_val END) AS lac_last_d2,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=0 THEN lab.med_val END) AS lac_med_d0,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=1 THEN lab.med_val END) AS lac_med_d1,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=2 THEN lab.med_val END) AS lac_med_d2,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=0 THEN lab.worst_val END) AS lac_worst_d0,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=1 THEN lab.worst_val END) AS lac_worst_d1,
  MAX(CASE WHEN lab.labname='lactate' AND lab.day=2 THEN lab.worst_val END) AS lac_worst_d2,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=0 THEN lab.last_val END) AS bili_last_d0,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=1 THEN lab.last_val END) AS bili_last_d1,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=2 THEN lab.last_val END) AS bili_last_d2,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=0 THEN lab.med_val END) AS bili_med_d0,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=1 THEN lab.med_val END) AS bili_med_d1,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=2 THEN lab.med_val END) AS bili_med_d2,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=0 THEN lab.worst_val END) AS bili_worst_d0,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=1 THEN lab.worst_val END) AS bili_worst_d1,
  MAX(CASE WHEN lab.labname='total bilirubin' AND lab.day=2 THEN lab.worst_val END) AS bili_worst_d2,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=0 THEN lab.last_val END) AS wbc_last_d0,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=1 THEN lab.last_val END) AS wbc_last_d1,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=2 THEN lab.last_val END) AS wbc_last_d2,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=0 THEN lab.med_val END) AS wbc_med_d0,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=1 THEN lab.med_val END) AS wbc_med_d1,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=2 THEN lab.med_val END) AS wbc_med_d2,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=0 THEN lab.worst_val END) AS wbc_worst_d0,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=1 THEN lab.worst_val END) AS wbc_worst_d1,
  MAX(CASE WHEN lab.labname='WBC x 1000' AND lab.day=2 THEN lab.worst_val END) AS wbc_worst_d2,
  MAX(CASE WHEN m.day=0 THEN m.map_med END) AS map_med_d0,
  MAX(CASE WHEN m.day=0 THEN m.map_worst END) AS map_worst_d0,
  MAX(CASE WHEN m.day=1 THEN m.map_med END) AS map_med_d1,
  MAX(CASE WHEN m.day=1 THEN m.map_worst END) AS map_worst_d1,
  MAX(CASE WHEN m.day=2 THEN m.map_med END) AS map_med_d2,
  MAX(CASE WHEN m.day=2 THEN m.map_worst END) AS map_worst_d2,
  MAX(CASE WHEN u.day=0 THEN u.urine_ml END) AS urine_d0,
  MAX(CASE WHEN u.day=1 THEN u.urine_ml END) AS urine_d1,
  MAX(CASE WHEN u.day=2 THEN u.urine_ml END) AS urine_d2
FROM eicu_sepsis_cohort c
LEFT JOIN (
  SELECT patientunitstayid AS stay_id, labname, day, last_val, med_val,
    CASE WHEN labname='platelets x 1000' THEN min_val ELSE max_val END AS worst_val
  FROM eicu_p3b_lab_daily
) lab ON lab.stay_id = c.stay_id
LEFT JOIN eicu_p3b_map_daily m ON m.stay_id = c.stay_id
LEFT JOIN eicu_p3b_urine_daily u ON u.patientunitstayid = c.stay_id
GROUP BY c.stay_id;